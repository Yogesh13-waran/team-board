"""
Views for TeamBoard API.

================================================================================
INTERVIEW DEEP-DIVE: ARCHITECTURE, ORM, AND API DESIGN
================================================================================
1. DRF APIView vs ViewSet:
   - For custom business logic, explicit RPC-style workflows, or specialized analytics,
     subclassing `APIView` provides exact control over HTTP method handlers (`get`, `post`),
     explicit request parsing, custom authentication overrides, and crisp error handling.

2. Database Transactions & ACID Guarantees (`transaction.atomic()`):
   - Atomicity: "All or nothing". In `KBQueryView`, we execute the search and persist
     the `QueryLog` inside a single `transaction.atomic()` context manager.
   - If an unexpected error occurs during log insertion (e.g. database disk full or lock timeout),
     the database issues a ROLLBACK to the savepoint, guaranteeing the search operation
     and audit trail remain completely consistent.
   - Interview Question: "What happens if an exception is raised inside transaction.atomic()?"
     Answer: Django intercepts the exception, rolls back the transaction (or subtransaction
     savepoint in nested blocks), and re-raises the exception.

3. Q Objects & Case-Insensitive Filter (`icontains`):
   - Standard Django filter kwargs are joined via SQL `AND`:
     `KBEntry.objects.filter(question__icontains=x, answer__icontains=x)` -> `WHERE q ILIKE %x% AND a ILIKE %x%`.
   - To perform a logical `OR`, Django provides `django.db.models.Q` objects:
     `Q(question__icontains=x) | Q(answer__icontains=x)` -> `WHERE q ILIKE %x% OR a ILIKE %x%`.
   - In PostgreSQL, `__icontains` translates to the native `ILIKE` operator, which
     respects case insensitivity across ASCII and Unicode characters.

4. Django ORM: `aggregate()` vs `annotate()`:
   - `aggregate()`:
     * Computes a summary value across the ENTIRE queryset (reduces table to a single row/scalar).
     * SQL equivalent: `SELECT COUNT(id) AS total FROM api_querylog;`
   - `annotate()`:
     * Computes per-group or per-object calculations (SQL `GROUP BY`).
     * `values('search_term').annotate(count=Count('id')).order_by('-count')[:5]`
     * SQL equivalent:
       `SELECT search_term, COUNT(id) AS count FROM api_querylog GROUP BY search_term ORDER BY count DESC LIMIT 5;`

5. Authentication & Security:
   - `request.user.company` extraction guarantees tenancy. We NEVER trust a `company_id`
     passed in the client request body, preventing Insecure Direct Object References (IDOR).
================================================================================
"""

from django.contrib.auth import authenticate
from django.contrib.auth.models import User
from django.db import transaction
from django.db.models import Count, Q
from rest_framework import status
from rest_framework.response import Response
from rest_framework.views import APIView
from rest_framework_simplejwt.tokens import RefreshToken

from .models import Company, KBEntry, QueryLog
from .permissions import IsAdminUser
from .serializers import (
    KBEntrySerializer,
    KBQueryRequestSerializer,
    LoginSerializer,
    RegisterSerializer,
)


class RegisterView(APIView):
    """
    POST /api/auth/register/

    Public endpoint allowing new B2B companies to register.
    Creates a User record, relies on post_save signal to auto-create Company
    and generate API key, updates company name, and returns a fresh JWT access token.
    """
    authentication_classes = []
    permission_classes = []

    def post(self, request):
        serializer = RegisterSerializer(data=request.data)
        if not serializer.is_valid():
            return Response(serializer.errors, status=status.HTTP_400_BAD_REQUEST)

        username = serializer.validated_data['username']
        password = serializer.validated_data['password']
        company_name = serializer.validated_data['company_name']
        email = serializer.validated_data['email']

        # Atomic block ensures User and Company state updates are committed together
        with transaction.atomic():
            # 1. Create User - triggers post_save signal in signals.py
            user = User.objects.create_user(
                username=username,
                email=email,
                password=password
            )

            # 2. Retrieve auto-created Company profile generated by signal
            company = user.company

            # 3. Update company_name from client request payload
            # role remains default CLIENT, api_key was generated by secrets.token_urlsafe(32)
            company.company_name = company_name
            company.save(update_fields=['company_name'])

        # 4. Generate JWT access token for immediate API access
        refresh = RefreshToken.for_user(user)
        access_token = str(refresh.access_token)

        response_data = {
            "username": user.username,
            "company_name": company.company_name,
            "api_key": company.api_key,
            "access": access_token
        }
        return Response(response_data, status=status.HTTP_201_CREATED)


class LoginView(APIView):
    """
    POST /api/auth/login/

    Public endpoint allowing registered companies to log in with username & password.
    Returns a fresh JWT access token along with company credentials (name and API key).
    """
    authentication_classes = []
    permission_classes = []

    def post(self, request):
        serializer = LoginSerializer(data=request.data)
        if not serializer.is_valid():
            return Response(serializer.errors, status=status.HTTP_400_BAD_REQUEST)

        username = serializer.validated_data['username']
        password = serializer.validated_data['password']

        # Authenticate credentials using Django's password hasher
        user = authenticate(request, username=username, password=password)

        if user is None or not user.is_active:
            return Response(
                {"detail": "Invalid credentials. Please verify your username and password."},
                status=status.HTTP_401_UNAUTHORIZED
            )

        if not hasattr(user, 'company'):
            return Response(
                {"detail": "No company profile found for this user account."},
                status=status.HTTP_400_BAD_REQUEST
            )

        company = user.company
        refresh = RefreshToken.for_user(user)
        access_token = str(refresh.access_token)

        response_data = {
            "access": access_token,
            "company_name": company.company_name,
            "api_key": company.api_key
        }
        return Response(response_data, status=status.HTTP_200_OK)


class KBQueryView(APIView):
    """
    POST /api/kb/query/

    Protected endpoint allowing authenticated companies to search the knowledge base.
    Uses Q objects to search question & answer fields case-insensitively.
    Wraps search and QueryLog creation in a single transaction.atomic() block.
    """

    def post(self, request):
        # 1. Tenancy validation: extract company from authenticated user
        if not hasattr(request.user, 'company'):
            return Response(
                {"detail": "Authenticated user is not linked to any registered company."},
                status=status.HTTP_403_FORBIDDEN
            )
        company = request.user.company

        # 2. Validate search term payload
        serializer = KBQueryRequestSerializer(data=request.data)
        if not serializer.is_valid():
            # Return 400 if search field is missing or blank
            return Response(serializer.errors, status=status.HTTP_400_BAD_REQUEST)

        search_term = serializer.validated_data['search']

        # 3. Construct Q objects for case-insensitive search across question & answer
        query = Q(question__icontains=search_term) | Q(answer__icontains=search_term)

        # 4. Atomic execution: execute search, count results, and record QueryLog
        with transaction.atomic():
            matching_entries = list(KBEntry.objects.filter(query).order_by('id'))
            count = len(matching_entries)

            # Usage tracking: QueryLog must be written even when count is 0
            QueryLog.objects.create(
                company=company,
                search_term=search_term,
                results_count=count
            )

        # 5. Serialize matching results
        results_data = KBEntrySerializer(matching_entries, many=True).data

        return Response({
            "search": search_term,
            "count": count,
            "results": results_data
        }, status=status.HTTP_200_OK)


class AdminUsageSummaryView(APIView):
    """
    GET /api/admin/usage-summary/

    Protected platform admin dashboard endpoint.
    Restricted to users whose Company has role=ADMIN via IsAdminUser.
    Computes total queries, active companies, and top 5 search terms using ORM aggregations.
    """
    permission_classes = [IsAdminUser]

    def get(self, request):
        # 1. Total queries ever made across the platform
        total_queries = QueryLog.objects.aggregate(total=Count('id'))['total'] or 0

        # 2. Number of distinct companies that have issued queries
        active_companies = QueryLog.objects.values('company').distinct().count()

        # 3. Top 5 most-searched terms using GROUP BY + annotate + order_by + slice
        top_search_terms_qs = (
            QueryLog.objects.values('search_term')
            .annotate(count=Count('id'))
            .order_by('-count')[:5]
        )
        top_search_terms = list(top_search_terms_qs)

        return Response({
            "total_queries": total_queries,
            "active_companies": active_companies,
            "top_search_terms": top_search_terms
        }, status=status.HTTP_200_OK)
